import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import React from 'react';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
const mocks = vi.hoisted(() => ({ list: vi.fn(), roster: vi.fn(), create: vi.fn(), update: vi.fn() }));
vi.mock('../../lib/api/branchEvent', async importOriginal => ({ ...await importOriginal<object>(), listOperatorEvents: mocks.list, listEventRsvps: mocks.roster, createEvent: mocks.create, updateEvent: mocks.update }));
import EventsPage from './EventsPage';
const event = (title: string) => ({ id: title, title, status: 'draft', startsAt: '2026-10-11T00:00:00Z', visibility: 'members_only', rsvpEnabled: true, rsvpOpen: true, counts: { attending: 1, notAttending: 0 } });
beforeEach(() => { vi.resetAllMocks(); vi.stubGlobal('React', React); });
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });
it('a branch change clears the old editor and ignores its late list response', async () => {
  let old!: (data: unknown) => void;
  mocks.list.mockImplementationOnce(() => new Promise(done => { old = done; })).mockResolvedValueOnce([event('B 행사')]);
  const view = render(<EventsPage slug="branch-a" />);
  fireEvent.click(screen.getByRole('button', { name: '행사 만들기' }));
  fireEvent.change(screen.getByPlaceholderText('예: 2026년 정기총회'), { target: { value: 'A 초안' } });
  view.rerender(<EventsPage slug="branch-b" />);
  await screen.findByText('B 행사');
  expect(screen.queryByDisplayValue('A 초안')).toBeNull();
  await act(async () => old([event('A 늦은 행사')]));
  expect(screen.queryByText('A 늦은 행사')).toBeNull();
  expect(mocks.list).toHaveBeenLastCalledWith('branch-b', null);
});
it('out-of-order event rosters cannot replace the currently opened event', async () => {
  let old!: (data: unknown) => void;
  mocks.list.mockResolvedValue([event('첫 행사'), event('둘째 행사')]);
  mocks.roster.mockImplementationOnce(() => new Promise(done => { old = done; })).mockResolvedValueOnce({ items: [{ userId: 'b', name: '둘째 명단', status: 'attending', respondedAt: '2026-10-11' }] });
  render(<EventsPage slug="branch-a" />);
  await screen.findByText('첫 행사');
  const buttons = screen.getAllByRole('button', { name: '참가명단' });
  fireEvent.click(buttons[0]); fireEvent.click(buttons[1]);
  await screen.findByText('둘째 명단');
  await act(async () => old({ items: [{ userId: 'a', name: '이전 명단', status: 'attending' }] }));
  expect(screen.queryByText('이전 명단')).toBeNull();
});
it('status-filter late responses cannot restore the previous event list', async () => {
  let old!: (data: unknown) => void;
  mocks.list.mockImplementationOnce(() => new Promise(done => { old = done; })).mockResolvedValueOnce([]);
  render(<EventsPage slug="branch-a" />);
  fireEvent.change(screen.getByRole('combobox', { name: '행사 상태' }), { target: { value: 'published' } });
  await screen.findByText('등록된 행사가 없습니다.');
  await act(async () => old([event('옛 필터 행사')]));
  expect(screen.queryByText('옛 필터 행사')).toBeNull();
});
it('read failure can retry and duplicate saves are blocked', async () => {
  let complete!: () => void;
  mocks.list.mockRejectedValueOnce(new Error('fixture')).mockResolvedValue([]);
  mocks.create.mockImplementation(() => new Promise<void>(done => { complete = done; }));
  render(<EventsPage slug="branch-a" />);
  await screen.findByRole('alert');
  fireEvent.click(screen.getByRole('button', { name: '목록 다시 조회' }));
  await screen.findByText('등록된 행사가 없습니다.');
  fireEvent.click(screen.getByRole('button', { name: '행사 만들기' }));
  const save = screen.getByRole('button', { name: '저장' });
  fireEvent.click(save); fireEvent.click(save);
  expect(mocks.create).toHaveBeenCalledTimes(1);
  expect((screen.getByRole('combobox', { name: '행사 상태' }) as HTMLSelectElement).disabled).toBe(true);
  await act(async () => complete());
  await waitFor(() => expect(screen.queryByRole('button', { name: '저장' })).toBeNull());
});

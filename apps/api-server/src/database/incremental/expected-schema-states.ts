/** Expected state after `prefixLength` incremental migrations; undefined when not registered. */
export function expectedSchemaStateFor(
  prefixLength: number,
  states: readonly ExpectedSchemaState[] = EXPECTED_SCHEMA_STATES,
): ExpectedSchemaState | undefined {
  if (!Number.isInteger(prefixLength) || prefixLength < 0) return undefined;
  return states[prefixLength];
}

/** Human label for a state (log lines). */
export function expectedSchemaStateLabel(state: ExpectedSchemaState | undefined): string {
  if (!state) return 'UNREGISTERED';
  return state.appliedThrough ?? `baseline ${CANONICAL_SCHEMA_BASELINE_META.baselineVersion}`;
}

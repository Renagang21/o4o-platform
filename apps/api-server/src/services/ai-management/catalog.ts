/** Read-only inventory. Entries describe source wiring, not live traffic or authority. */
export type SelectionMode =
  | "query"
  | "editing"
  | "editing-provider"
  | "runtime"
  | "strong"
  | "fixed"
  | "scope"
  | "environment"
  | "request"
  | "legacy-hub"
  | "tts";
export type AccountingCoverage = "connected" | "partial" | "unconnected";
export interface AiUsageDefinition {
  id: string;
  evidenceId: string;
  name: string;
  group:
    | "shared"
    | "neture"
    | "hospital"
    | "editor"
    | "product"
    | "store"
    | "kpa-society"
    | "lecture";
  capability: string;
  selection: SelectionMode;
  accounting: AccountingCoverage;
  stop: "query" | "scope" | "none";
  scope?: string;
  note: string;
  /** Some specialist/shared-policy consumers are observable without an independent model selector. */
  modelSelectable?: boolean;
}

function entry(
  evidenceId: string,
  id: string,
  name: string,
  group: AiUsageDefinition["group"],
  capability: string,
  selection: SelectionMode,
  accounting: AccountingCoverage,
  stop: AiUsageDefinition["stop"],
  note: string,
  scope?: string,
): AiUsageDefinition {
  return {
    evidenceId,
    id,
    name,
    group,
    capability,
    selection,
    accounting,
    stop,
    note,
    ...(scope ? { scope } : {}),
  };
}


import { afterEach, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { OperatorForumCategoriesPage } from '../OperatorForumCategoriesPage';
const category = { id: 'forum-a', name: '검증 포럼 A', slug: 'fixture-a', isActive: true, postCount: 0, forumType: 'open', tags: [], createdAt: '2026-10-15', updatedAt: '2026-10-15' };
const allowed = { postCount: 0, memberCount: 0, generalMemberCount: 0, ownerCount: 1, hardDeleteAllowed: true, blockedReasons: [], warnings: [] };
const client = () => ({ getCategories: vi.fn().mockResolvedValue({ data: [category] }), updateCategory: vi.fn().mockResolvedValue({ success: true }), directDeactivate: vi.fn().mockResolvedValue({ success: true }), activate: vi.fn().mockResolvedValue({ success: true }), getDeleteCheck: vi.fn().mockResolvedValue({ data: allowed }), hardDelete: vi.fn().mockResolvedValue({ success: true }) });
afterEach(() => { cleanup(); vi.restoreAllMocks(); localStorage.clear(); });
const open = async (name: string) => { await screen.findByText('검증 포럼 A'); fireEvent.click(screen.getByTitle('더보기')); fireEvent.click(screen.getByRole('button', { name })); };
it('preserves reason after failed deactivation, blocks close and duplicate requests while pending', async () => {
  const api = client(); let resolve!: (value: unknown) => void;
  api.directDeactivate.mockReturnValueOnce(new Promise(r => { resolve = r; }));
  render(<OperatorForumCategoriesPage client={api} />); await open('비활성화');
  const reason = screen.getByPlaceholderText('예: 테스트 포럼 정리, 중복 포럼 제거 등');
  fireEvent.change(reason, { target: { value: '중복 정리 사유' } });
  const submit = screen.getByRole('button', { name: '비활성화' });
  fireEvent.click(submit); fireEvent.click(submit);
  fireEvent.click(screen.getByRole('button', { name: '취소' }));
  expect(api.directDeactivate).toHaveBeenCalledTimes(1); expect(reason.isConnected).toBe(true);
  await act(async () => resolve({ success: false, error: '처리 거부' }));
  await screen.findAllByText('처리 거부');
  expect((reason as HTMLTextAreaElement).value).toBe('중복 정리 사유');
  fireEvent.click(submit);
  await waitFor(() => expect(api.directDeactivate).toHaveBeenCalledTimes(2));
  expect(api.directDeactivate.mock.calls[1]).toEqual(['forum-a', { reason: '중복 정리 사유' }]);
});
it('keeps the tag draft on failure and refreshes only after success', async () => {
  const api = client(); api.updateCategory.mockResolvedValueOnce({ success: false, error: '태그 실패' });
  render(<OperatorForumCategoriesPage client={api} />); await open('태그 수정');
  const input = screen.getByPlaceholderText('태그 입력 (Enter/쉼표)');
  fireEvent.change(input, { target: { value: '검증태그' } }); fireEvent.keyDown(input, { key: 'Enter' });
  fireEvent.click(screen.getByRole('button', { name: '저장' })); await screen.findAllByText('태그 실패');
  expect(screen.getByText('검증태그')).toBeTruthy(); expect(api.getCategories).toHaveBeenCalledTimes(1);
  fireEvent.click(screen.getByRole('button', { name: '저장' }));
  await waitFor(() => expect(api.getCategories).toHaveBeenCalledTimes(2));
  expect(api.updateCategory.mock.calls[1]).toEqual(['forum-a', { tags: ['검증태그'] }]);
});
it('ignores a delete-check response after the modal is closed and reopened', async () => {
  const api = client(); api.getCategories.mockResolvedValue({ data: [{ ...category, isActive: false }] });
  let resolve!: (value: unknown) => void;
  api.getDeleteCheck.mockReturnValueOnce(new Promise(r => { resolve = r; }));
  render(<OperatorForumCategoriesPage client={api} />); await open('완전 삭제');
  fireEvent.click(screen.getByRole('button', { name: '취소' }));
  await open('완전 삭제');
  await screen.findByPlaceholderText('예: 테스트 포럼 영구 정리, 오등록 포럼 제거 등');
  await act(async () => resolve({ data: { ...allowed, hardDeleteAllowed: false, blockedReasons: ['이전 응답 차단'] } }));
  expect(screen.queryByText('이전 응답 차단')).toBeNull(); expect(api.hardDelete).not.toHaveBeenCalled();
});
it('ignores a mutation completion after switching the client scope', async () => {
  const api = client(); let resolve!: (value: unknown) => void;
  api.directDeactivate.mockReturnValueOnce(new Promise(r => { resolve = r; }));
  const view = render(<OperatorForumCategoriesPage client={api} />); await open('비활성화');
  fireEvent.change(screen.getByPlaceholderText('예: 테스트 포럼 정리, 중복 포럼 제거 등'), { target: { value: '검증' } });
  fireEvent.click(screen.getByRole('button', { name: '비활성화' }));
  const next = client(); next.getCategories.mockResolvedValue({ data: [{ ...category, name: '새 범위 포럼' }] });
  view.rerender(<OperatorForumCategoriesPage client={next} tableId="next" />); await screen.findByText('새 범위 포럼');
  await act(async () => resolve({ success: true }));
  expect(screen.queryByText(/포럼이 비활성화되었습니다/)).toBeNull(); expect(api.getCategories).toHaveBeenCalledTimes(1);
  expect(next.getCategories).toHaveBeenCalledTimes(1);
});
it('batch retry writes only failed targets and refreshes without waiting for result modal close', async () => {
  vi.spyOn(window, 'prompt').mockReturnValue('일괄 검증');
  const api = client(); api.getCategories.mockResolvedValue({ data: [category, { ...category, id: 'forum-b', name: '검증 포럼 B' }] });
  api.directDeactivate.mockImplementation(async id => ({ success: id === 'forum-a', error: id === 'forum-b' ? '실패 B' : undefined }));
  render(<OperatorForumCategoriesPage client={api} />); await screen.findByText('검증 포럼 A');
  fireEvent.click(screen.getAllByRole('checkbox')[0]);
  fireEvent.click(screen.getByRole('button', { name: '비활성화 (2)' }));
  await screen.findByText(/1건 완료 · 1건 실패/);
  await waitFor(() => expect(api.getCategories).toHaveBeenCalledTimes(2));
  api.directDeactivate.mockResolvedValue({ success: true });
  fireEvent.click(screen.getByRole('button', { name: /실패.*재시도/ }));
  await waitFor(() => expect(api.directDeactivate).toHaveBeenCalledTimes(3));
  expect(api.directDeactivate.mock.calls[2][0]).toBe('forum-b');
  await waitFor(() => expect(api.getCategories).toHaveBeenCalledTimes(3));
});
it('retains the hard-delete reason when the server blocks the final write', async () => {
  const api = client(); api.getCategories.mockResolvedValue({ data: [{ ...category, isActive: false }] });
  api.hardDelete.mockRejectedValue({ response: { data: { data: { blockedReasons: ['보호 대상 존재'] } } } });
  render(<OperatorForumCategoriesPage client={api} />); await open('완전 삭제');
  const reason = await screen.findByPlaceholderText('예: 테스트 포럼 영구 정리, 오등록 포럼 제거 등');
  fireEvent.change(reason, { target: { value: '검증 삭제 사유' } });
  fireEvent.click(screen.getByRole('button', { name: '영구 삭제' }));
  await screen.findAllByText('삭제 불가: 보호 대상 존재');
  expect((reason as HTMLTextAreaElement).value).toBe('검증 삭제 사유');
  expect(api.getDeleteCheck).toHaveBeenCalledWith('forum-a');
  expect(api.getCategories).toHaveBeenCalledTimes(1);
});
